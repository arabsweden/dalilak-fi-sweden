/**
 * Returns today's phrase deterministically based on date, or falls back to an index
 */
export function getDailyPhrase(offset: number = 0): DailyPhrase {
  const now = new Date();
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  const index = Math.abs(dayOfYear + offset) % ESSENTIAL_SWEDISH_PHRASES.length;
  return ESSENTIAL_SWEDISH_PHRASES[index];
}
